def grs80_radii(lat_deg):
    a, f = 6378137.0, 1.0 / 298.257222101
    e2 = f * (2 - f)
    s = math.sin(math.radians(lat_deg))
    w = math.sqrt(1 - e2 * s * s)
    return a * (1 - e2) / w ** 3, a / w     # M, N


def neu_metres(lat_a, lonw_a, h_a, lat_b, lonw_b, h_b):
    """(a - b) as north, east, up metres; longitude positive west."""
    m, n = grs80_radii(lat_b)
    dn = math.radians(lat_a - lat_b) * m
    de = -math.radians(lonw_a - lonw_b) * n * math.cos(math.radians(lat_b))
    return dn, de, h_a - h_b


