class Const:
    """The mutable /CONST/ common block; ELPSD selects the ellipsoid."""

    def __init__(self):
        self.elpsd = "GRS80"              # htdp.f:60
        self.model()

    def model(self):                      # htdp.f:151-163
        a = 6378137.0
        f = 1.0 / 298.257222101
        if self.elpsd == "WGS84":
            f = 1.0 / 298.257223563       # htdp.f:154
        self.A = a
        self.F = f
        self.E2 = f * (2.0 - f)           # htdp.f:161
        self.AF = a / (1.0 - f)           # htdp.f:162
        self.EPS = f * (2.0 - f) / ((1.0 - f) * (1.0 - f))   # htdp.f:163 (**2)


