    hdr_ok = all(s in hdr for s in ("GRDLX( 6) / 250.00000000000", "GRDUX( 6) / 294.00000000000",
                                    "GRDLY( 6) /  24.00000000000", "GRDUY( 6) /  50.00000000000",
                                    "ICNTX( 6) / 88", "ICNTY( 6) / 52", "NBASE( 6) /128808"))
    with open(src + "/initeq.f", encoding="latin1") as fh:
        eq = fh.read()
    got = []
    for name in ("EQLATR", "EQLONR", "EQRAD", "ITEQK"):
        got.append({int(a): b for a, b in re.findall(name + r"\(\s*(\d+)\)\s*/\s*([-0-9.E+]+)\s*/", eq)})
    eq_bad = sum(1 for k, row in enumerate(EQS, 1)
                 if tuple(float(got[q][k]) for q in range(4)) != tuple(float(v) for v in row))
    numeq_ok = re.search(r"DATA NUMEQ\s*/\s*33\s*/", eq) is not None
    print("transcription check: grid nodes %d, mismatches %d, header ok %s; EQs %d, mismatches %d, NUMEQ=33 %s"
          % (len(VGRID6), bad, hdr_ok, len(EQS), eq_bad, numeq_ok))
    return bad == 0 and hdr_ok and eq_bad == 0 and numeq_ok


