def grdwei(ylon, ylat):              # htdp.f:1542-1631 for JREGN=6
    posx = (TWOPI - ylon) * 180.0 / PI
    posy = ylat * 180.0 / PI
    stepx = (G6_UX - G6_LX) / G6_NX
    stepy = (G6_UY - G6_LY) / G6_NY
    i = int((posx - G6_LX) / stepx) + 1
    j = int((posy - G6_LY) / stepy) + 1
    grlx = G6_LX + (i - 1) * stepx
    grux = grlx + stepx
    grly = G6_LY + (j - 1) * stepy
    gruy = grly + stepy
    denom = (grux - grlx) * (gruy - grly)
    w11 = (grux - posx) * (gruy - posy) / denom
    w21 = (posx - grlx) * (gruy - posy) / denom
    w12 = (grux - posx) * (posy - grly) / denom
    w22 = (posx - grlx) * (posy - grly) / denom
    return i, j, w11, w12, w21, w22


