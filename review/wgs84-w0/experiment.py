def iymdmj(iyr, imon, iday):         # htdp.f:7997-8084
    iyrp = iyr
    if imon < 3:
        iyrp = iyrp - 1
        imop = imon + 12
    else:
        imop = imon
    a = int(float(iyrp) * 0.01)
    b = 2 - a + int(float(a) * 0.25)
    cc = int(365.25 * float(iyrp))
    d = int(30.6001 * float(imop + 1))
    return b + cc + d + iday - 679006


