def toxyz(c, glat, glon, eht):       # htdp.f:895-916 (calls MODEL, :904)
    c.model()
    slat = math.sin(glat)
    clat = math.cos(glat)
    w = math.sqrt(1.0 - c.E2 * slat * slat)
    en = c.A / w
    x = (en + eht) * clat * math.cos(glon)
    y = (en + eht) * clat * math.sin(glon)
    z = (en * (1.0 - c.E2) + eht) * slat
    return x, y, z


def frmxyz(c, x, y, z):              # htdp.f:919-974 (maxint=10, tol=1e-13, :926)
    c.model()
    ae2 = c.A * c.E2
    p = math.sqrt(x * x + y * y)
    icount = 0
    tgla = z / p / (1.0 - c.E2)
    while True:
        if icount <= 10:
            tglax = tgla
            tgla = z / (p - (ae2 / math.sqrt(1.0 + (1.0 - c.E2) * tgla * tgla)))
            icount += 1
            if abs(tgla - tglax) > 1.0e-13:
                continue
            glat = math.atan(tgla)
            slat = math.sin(glat)
            clat = math.cos(glat)
            w = math.sqrt(1.0 - c.E2 * slat * slat)
            en = c.A / w
            if abs(glat) <= 0.7854:          # htdp.f:957 -- switch at ~45.0000 N
                eht = p / clat - en
            else:
                eht = z / slat - en + c.E2 * en
            glon = math.atan2(y, x)
            return glat, glon, eht
        raise RuntimeError("FRMXYZ failed (HTDP would STOP 666)")


def radii(c, ylat):                  # htdp.f:976-988 (no MODEL call: uses current /CONST/)
    coslat = math.cos(ylat)
    denom = math.sqrt(1.0 + c.EPS * coslat * coslat)
    d3 = denom * denom * denom
    return c.AF / d3, c.AF * coslat / denom


def tovneu(glat, glon, vx, vy, vz):  # htdp.f:1747-1764
    slat, clat, slon, clon = math.sin(glat), math.cos(glat), math.sin(glon), math.cos(glon)
    vn = -slat * clon * vx - slat * slon * vy + clat * vz
    ve = -slon * vx + clon * vy
    vu = clat * clon * vx + clat * slon * vy + slat * vz
    return vn, ve, vu


def tovxyz(glat, glon, vn, ve, vu):  # htdp.f:1767-1782
    slat, clat, slon, clon = math.sin(glat), math.cos(glat), math.sin(glon), math.cos(glon)
    vx = -slat * clon * vn - slon * ve + clat * clon * vu
    vy = -slat * slon * vn + clon * ve + clat * slon * vu
    vz = clat * vn + slat * vu
    return vx, vy, vz


