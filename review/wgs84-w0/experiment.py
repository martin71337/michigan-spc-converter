def _cook(raw):
    out = {}
    for k, p in raw.items():
        (tx, ty, tz, dtx, dty, dtz, rx, ry, rz, drx, dry, drz, sc, dsc, ref) = p
        out[k] = dict(tx=tx, ty=ty, tz=tz, dtx=dtx, dty=dty, dtz=dtz,
                      rx=rx / RHOSEC, ry=ry / RHOSEC, rz=rz / RHOSEC,
                      drx=drx / RHOSEC, dry=dry / RHOSEC, drz=drz / RHOSEC,
                      scale=sc, dscale=dsc, refepc=ref)
    return out


