def getmdy(entry):
    """Returns (DATE decimal years, MINS, (month, day, year)) exactly as GETMDY."""
    if isinstance(entry, (list, tuple)):            # option 1, htdp.f:7886-7922
        month, iday, iyear = entry
        if iyear <= 1906 or not (1 <= month <= 12) or not (1 <= iday <= 31):
            raise ValueError("GETMDY refuses %r" % (entry,))
        mjd = iymdmj(iyear, month, iday)
        mjd0 = iymdmj(iyear, 1, 1)
        mjd1 = iymdmj(iyear + 1, 1, 1)
        day = float(mjd - mjd0)
        denom = float(mjd1 - mjd0)
        date = float(iyear) + (day / denom)
        return date, mjd * 24 * 60, (month, iday, iyear)
    date = float(entry)                             # option 2, htdp.f:7924-7970
    if date < 1906.0:
        raise ValueError("GETMDY refuses %r" % entry)
    iyear = int(date)
    mjd0 = iymdmj(iyear, 1, 1)
    mjd1 = iymdmj(iyear + 1, 1, 1)
    leap = 1 if (mjd1 - mjd0) == 366 else 0
    remday = (date - float(iyear)) * float(mjd1 - mjd0)
    ibegin = 0
    itotal = 31
    if remday < itotal:
        month = 1
        iday = int(remday) - ibegin + 1
        return date, iymdmj(iyear, month, iday) * 24 * 60, (month, iday, iyear)
    ibegin = itotal
    itotal = itotal + leap
    for i in range(2, 13):
        itotal = itotal + _MDAYS[i - 1]
        if remday < itotal:
            iday = int(remday) - ibegin + 1
            return date, iymdmj(iyear, i, iday) * 24 * 60, (i, iday, iyear)
        ibegin = itotal
    raise ValueError("GETMDY could not convert %r" % entry)


