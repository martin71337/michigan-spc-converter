def f32(v):
    """A Fortran REAL literal (no D exponent) stored into a DOUBLE variable via
    DATA keeps single-precision value (verified with gfortran 13.3, RECON.md §7).
    Applies to initbd.f vertices, initvl.f grid values, initeq.f parameters."""
    return struct.unpack("f", struct.pack("f", v))[0]


