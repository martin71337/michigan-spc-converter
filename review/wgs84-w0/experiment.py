def frit94(t, xyz, date, iopt):      # htdp.f:4475-4521 (and _IERS 4523-4569)
    p = t[iopt]
    x1, y1, z1 = xyz
    dtime = date - p["refepc"]
    tranx = p["tx"] + p["dtx"] * dtime
    trany = p["ty"] + p["dty"] * dtime
    tranz = p["tz"] + p["dtz"] * dtime
    rotnx = p["rx"] + p["drx"] * dtime
    rotny = p["ry"] + p["dry"] * dtime
    rotnz = p["rz"] + p["drz"] * dtime
    ds = 1.0 + p["scale"] + p["dscale"] * dtime
    x2 = tranx + ds * x1 + rotnz * y1 - rotny * z1
    y2 = trany - rotnz * x1 + ds * y1 + rotnx * z1
    z2 = tranz + rotny * x1 - rotnx * y1 + ds * z1
    return x2, y2, z2


def toit94(t, xyz, date, iopt):      # htdp.f:4572-4617 (and _IERS 4620-4665)
    p = t[iopt]
    x1, y1, z1 = xyz
    dtime = date - p["refepc"]
    tranx = -(p["tx"] + p["dtx"] * dtime)
    trany = -(p["ty"] + p["dty"] * dtime)
    tranz = -(p["tz"] + p["dtz"] * dtime)
    rotnx = -(p["rx"] + p["drx"] * dtime)
    rotny = -(p["ry"] + p["dry"] * dtime)
    rotnz = -(p["rz"] + p["drz"] * dtime)
    ds = 1.0 - (p["scale"] + p["dscale"] * dtime)
    x2 = tranx + ds * x1 + rotnz * y1 - rotny * z1
    y2 = trany - rotnz * x1 + ds * y1 + rotnx * z1
    z2 = tranz + rotny * x1 - rotnx * y1 + ds * z1
    return x2, y2, z2


def vtranf(t, X, Y, Z, vx, vy, vz, i1, i2):   # htdp.f:7666-7728 (and _IERS 7730-7791)
    vx = vx / 1000.0
    vy = vy / 1000.0
    vz = vz / 1000.0
    p = t[i1]
    wx, wy, wz, ds = -p["drx"], -p["dry"], -p["drz"], -p["dscale"]
    vx = vx - p["dtx"] + ds * X + wz * Y - wy * Z
    vy = vy - p["dty"] - wz * X + ds * Y + wx * Z
    vz = vz - p["dtz"] + wy * X - wx * Y + ds * Z
    p = t[i2]
    wx, wy, wz, ds = p["drx"], p["dry"], p["drz"], p["dscale"]
    vx = vx + p["dtx"] + ds * X + wz * Y - wy * Z
    vy = vy + p["dty"] - wz * X + ds * Y + wx * Z
    vz = vz + p["dtz"] + wy * X - wx * Y + ds * Z
    return vx * 1000.0, vy * 1000.0, vz * 1000.0


