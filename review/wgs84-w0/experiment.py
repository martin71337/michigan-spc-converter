    if y0 < 0.0:
        y0 = y0 + TWOPI
    for ir in range(1, 7):
        X, Y = REGIONS[ir]
        if polyin(x0, y0, X, Y) != 0:
            return ir
    # Not in regions 1-6. Regions 7-13 are Alaska / degenerate placeholders
    # (initbd.f:41-69); north of 50 N in this longitude band the next match is
    # region 14, the North America plate polygon (initbd.f:86ff). That polygon is
    # NOT transcribed: assumed, and used ONLY for the beyond-box probes.
    if math.degrees(x0) > 50.0 and 250.0 <= math.degrees(y0) <= 294.0:
        return 14
    raise RuntimeError("point outside transcribed regions: lat %.6f elon %.6f"
                       % (math.degrees(x0), math.degrees(y0)))


