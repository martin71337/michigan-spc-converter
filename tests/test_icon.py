def test_the_loader_looks_exactly_where_the_generator_writes():
    """One authoritative path, checked rather than remembered.

    The whole reason the .ico is generated instead of committed is that a second
    copy would drift from the master (docs/DESIGN.md amendment #15 note 1). That
    argument only holds while the loader reads the file the build step writes,
    so a change to either path has to change both or fail here.
    """
    assert make_icon.DEFAULT_OUTPUT == icon.GENERATED_ICO
    assert make_icon.MASTER_PNG == icon.MASTER_PNG
    assert icon.GENERATED_ICO in icon.icon_candidates()
    assert icon.MASTER_PNG in icon.icon_candidates()


def test_the_generated_icon_is_preferred_over_the_master(tmp_path, monkeypatch):
    """The .ico carries six hand-sized renderings; the PNG is one 1024 px image
    Qt would have to scale. When both exist the derived one wins."""
    generated = tmp_path / "coord-convert.ico"
    generated.write_bytes(b"stand-in")
    master = tmp_path / "coord-convert-1024.png"
    master.write_bytes(b"stand-in")

    monkeypatch.setattr(icon, "GENERATED_ICO", generated)
    monkeypatch.setattr(icon, "MASTER_PNG", master)

    assert icon.icon_path() == generated


def test_the_master_is_the_fallback_when_the_build_step_has_not_run(
    tmp_path, monkeypatch
):
    """A fresh clone still shows the owner's artwork."""
    monkeypatch.setattr(icon, "GENERATED_ICO", tmp_path / "not-built.ico")
    assert icon.icon_path() == icon.MASTER_PNG


def test_a_frozen_bundle_looks_inside_itself_first(tmp_path, monkeypatch):
    """PyInstaller unpacks data beside the executable and points sys._MEIPASS at
    it; a frozen run must not read the developer's build folder
    (docs/method/TOOLING.md)."""
    monkeypatch.setattr(icon.sys, "_MEIPASS", str(tmp_path), raising=False)

    bundled = tmp_path / "assets" / "icon" / icon.GENERATED_ICO_NAME
    assert icon.icon_candidates()[0] == bundled

    bundled.parent.mkdir(parents=True)
    bundled.write_bytes(b"stand-in")
    assert icon.icon_path() == bundled


def test_the_loader_returns_a_null_icon_rather_than_raising(tmp_path, monkeypatch):
    """No artwork anywhere. The window still has to open.

    This is the one place in the program where falling back beats refusing:
    nothing about a coordinate depends on the icon, and refusing to launch over
    a missing decoration would be the tier sentence applied backwards.
    """
    monkeypatch.setattr(icon, "GENERATED_ICO", tmp_path / "not-built.ico")
    monkeypatch.setattr(icon, "MASTER_PNG", tmp_path / "no-master.png")

    assert icon.icon_path() is None
    assert icon.application_icon().isNull() is True


def test_the_path_helpers_are_not_vacuous():
    """Guard against the checks above passing because nothing was found.

    icon_candidates() returning an empty tuple would make several assertions
    above trivially true, so the shape is pinned here.
    """
    candidates = icon.icon_candidates()
    assert len(candidates) >= 2
    assert all(isinstance(path, Path) for path in candidates)
