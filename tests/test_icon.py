def read_ico_directory(data: bytes) -> list[dict]:
    """Parse an .ico's directory, independently of the writer."""
    reserved, kind, count = struct.unpack_from("<HHH", data, 0)
    if reserved != 0 or kind != 1:
        raise ValueError(f"not an icon file: reserved={reserved} type={kind}")

    entries = []
    for index in range(count):
        (width, height, colours, pad, planes, bits, length, offset) = (
            struct.unpack_from("<BBBBHHII", data, 6 + 16 * index)
        )
        entries.append(
            {
                "width": width or 256,  # 0 means 256
                "height": height or 256,
                "colours": colours,
                "pad": pad,
                "planes": planes,
                "bits": bits,
                "length": length,
                "offset": offset,
                "body": data[offset : offset + length],
            }
        )
    return entries


def test_the_ico_directory_is_laid_out_where_the_format_says():
    """Hand-derived from the ICONDIR/ICONDIRENTRY structures.

    One 16x16 image:

      ICONDIR       = 6 bytes (reserved, type, count)
      ICONDIRENTRY  = 16 bytes, so the image data starts at 6 + 16 = 22
      BITMAPINFOHEADER = 40 bytes
      colour bitmap = 16 * 16 * 4 = 1024 bytes of BGRA
      AND mask      = 1 bit per pixel, rows padded to 4 bytes:
                      ((16 + 31) // 32) * 4 = 4 bytes per row, 16 rows = 64
      image total   = 40 + 1024 + 64 = 1128
      file total    = 22 + 1128 = 1150
    """
    data = make_icon.build_ico({16: bytes(16 * 16 * 4)})

    assert len(data) == 1150
    (entry,) = read_ico_directory(data)
    assert entry["width"] == 16
    assert entry["height"] == 16
    assert entry["planes"] == 1
    assert entry["bits"] == 32
    assert entry["colours"] == 0
    assert entry["length"] == 1128
    assert entry["offset"] == 22

    # The DIB header describes the colour bitmap and the mask as one image, so
    # its height is twice the icon's (Microsoft's ICONIMAGE documentation).
    size, bmp_width, bmp_height, planes, bits, compression = struct.unpack_from(
        "<IiiHHI", entry["body"], 0
    )
    assert (size, bmp_width, bmp_height) == (40, 16, 32)
    assert (planes, bits, compression) == (1, 32, 0)


def test_a_256_pixel_entry_records_its_size_as_zero():
    """The directory's width and height are single bytes, so 256 is written as
    0 and every reader knows to expand it. Getting this wrong produces an icon
    Windows shows as 0x0."""
    data = make_icon.build_ico({256: bytes(256 * 256 * 4)})
    assert data[6] == 0  # width byte of the first entry
    assert data[7] == 0  # height byte
    assert read_ico_directory(data)[0]["width"] == 256


def test_the_colour_bitmap_is_bottom_up_bgra():
    """Hand-derived on a 2x2 whose four pixels are all different.

    The source rows, top-down RGBA, are the TINY_ROWS fixture. A DIB stores
    rows bottom-up and channels as B, G, R, A, so the first four bytes of the
    colour bitmap are the BOTTOM-left pixel - (0, 0, 255, 128), opaque-ish blue
    - written as B=255, G=0, R=0, A=128.
    """
    _, _, pixels = make_icon.decode_png_rgba8(png_bytes(2, 2, TINY_ROWS))
    body = make_icon.build_ico({2: bytes(pixels)})[6 + 16 :]
    colour = body[40:]

    assert tuple(colour[0:4]) == (255, 0, 0, 128)  # bottom-left, BGRA
    # bottom-right was fully transparent white: (255, 255, 255, 0)
    assert tuple(colour[4:8]) == (255, 255, 255, 0)
    # top-left was opaque red (255, 0, 0, 255) -> B=0, G=0, R=255, A=255
    assert tuple(colour[8:12]) == (0, 0, 255, 255)


