def test_the_span_weights_are_the_area_each_output_sample_covers():
    """Hand-derived from the definition of an area average.

    Reducing 4 samples to 2: output sample 0 covers source [0, 2) and output
    sample 1 covers [2, 4). Each covers two whole source samples, so each weight
    is 1/2 and each span starts at 0 and 2.

    Reducing 3 to 2: scale is 1.5, so output 0 covers [0, 1.5) - all of source
    0 and half of source 1 - and output 1 covers [1.5, 3.0) - half of source 1
    and all of source 2. Normalised by the 1.5 samples each covers, the weights
    are (1/1.5, 0.5/1.5) = (2/3, 1/3) and (1/3, 2/3).
    """
    assert make_icon._spans(4, 2) == [(0, (0.5, 0.5)), (2, (0.5, 0.5))]

    spans = make_icon._spans(3, 2)
    assert [start for start, _ in spans] == [0, 1]
    assert spans[0][1] == pytest.approx((2 / 3, 1 / 3))
    assert spans[1][1] == pytest.approx((1 / 3, 2 / 3))
    # Every span is a true average: its weights sum to one.
    for _, weights in make_icon._spans(1024, 48):
        assert sum(weights) == pytest.approx(1.0)


def test_the_resampler_averages_with_alpha_premultiplied():
    """The 2x2 fixture reduced to one pixel. Hand-derived.

    Premultiplied channel sums, each source pixel weighted 1/4 (half in each
    direction):

      red   x alpha: 255*255 = 65025 from the red pixel alone
      green x alpha: 255*255 = 65025 from the green pixel alone
      blue  x alpha: 255*128 = 32640 from the half-alpha blue pixel
      alpha:         255 + 255 + 128 + 0 = 638

    times 1/4: (16256.25, 16256.25, 8160.0, 159.5)

    Dividing the colour back out of the alpha it carries:

      red   = 16256.25 / 159.5 = 101.9201 -> 102
      green = 101.9201                    -> 102
      blue  =  8160.00 / 159.5 =  51.1599 ->  51
      alpha =                     159.5   -> 160

    The fully transparent white pixel contributes nothing to the colour, which
    is the whole point of premultiplying: a plain RGB average would have pulled
    the result toward white by a quarter and put a pale fringe on the artwork's
    edges at 16 px.
    """
    _, _, pixels = make_icon.decode_png_rgba8(png_bytes(2, 2, TINY_ROWS))
    reduced = make_icon.resample_area(pixels, 2, 2, 1, 1)

    assert bytes(reduced) == bytes([102, 102, 51, 160])


def test_a_uniform_image_survives_reduction_exactly():
    """An area average of identical samples is that sample, to the byte.

    This is where a rounding or clamping slip would show: the weights sum to
    1 only to within a few ULPs in doubles, so 255 can average to just over
    255 and wrap to 0 without the clamp in _to_byte.
    """
    pixel = bytes([255, 255, 255, 255])
    rows = [pixel * 8 for _ in range(8)]
    _, _, pixels = make_icon.decode_png_rgba8(png_bytes(8, 8, rows))

    for size in (4, 3, 2, 1):
        reduced = make_icon.resample_area(pixels, 8, 8, size, size)
        assert bytes(reduced) == pixel * size * size


def test_the_resampler_refuses_to_enlarge():
    """Upscaling would invent detail the master does not have."""
    _, _, pixels = make_icon.decode_png_rgba8(png_bytes(2, 2, TINY_ROWS))
    with pytest.raises(make_icon.IconError) as raised:
        make_icon.resample_area(pixels, 2, 2, 4, 4)
    assert "only reduces" in str(raised.value)


