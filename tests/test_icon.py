def test_the_decoder_returns_the_pixels_that_were_encoded():
    """Round trip against bytes this file wrote, not against the tool's own."""
    width, height, pixels = make_icon.decode_png_rgba8(png_bytes(2, 2, TINY_ROWS))

    assert (width, height) == (2, 2)
    assert bytes(pixels) == b"".join(TINY_ROWS)


def test_the_decoder_reverses_every_png_filter():
    """Filters 0-4, each producing the same known row.

    Hand-derived. The target row is four pixels of (10, 20, 30, 40) repeated,
    so with a 4-byte pixel every filter's predictor is exactly computable:

      Sub (1):     each byte minus the byte 4 back. First pixel has no left
                   neighbour, so it stays (10,20,30,40); the rest become 0.
      Up (2):      each byte minus the byte above. Row 0's predictor row is
                   zeros, so row 0 is stored as-is and row 1 becomes all 0.
      Average (3): row 1, predictor (left + above) >> 1. With left and above
                   both equal to the value itself, (v + v) >> 1 == v, so every
                   stored byte in row 1 is 0 except the first pixel, whose left
                   is 0: (0 + v) >> 1 == v >> 1, leaving v - (v >> 1).
      Paeth (4):   row 1, predictors left/above/upper-left all equal v for the
                   later pixels, so the stored byte is 0; the first pixel has
                   left = upper-left = 0 and above = v, so Paeth picks v (the
                   estimate 0 + v - 0 = v is nearest to above) and stores 0.
    """
    pixel = bytes([10, 20, 30, 40])
    row = pixel * 4

    # Filter 0 on both rows: the plain case.
    plain = make_icon.decode_png_rgba8(png_bytes(4, 2, [row, row]))[2]
    assert bytes(plain) == row * 2

    def decode_with_filters(scanlines: list[tuple[int, bytes]]) -> bytes:
        raw = b"".join(bytes([kind]) + data for kind, data in scanlines)
        return bytes(make_icon._unfilter(raw, len(row), len(scanlines)))

    # Sub: first pixel verbatim, the other three encoded as zero deltas.
    assert decode_with_filters([(1, pixel + bytes(12))]) == row
    # Up: row 0 verbatim (its predictor row is zeros), row 1 all zero deltas.
    assert decode_with_filters([(2, row), (2, bytes(16))]) == row * 2
    # Average: row 1's first pixel stores v - (v >> 1) = 10-5, 20-10, 30-15,
    # 40-20 = (5, 10, 15, 20); the rest store 0.
    assert (
        decode_with_filters([(0, row), (3, bytes([5, 10, 15, 20]) + bytes(12))])
        == row * 2
    )
    # Paeth: row 1 stores nothing but zeros and still reproduces the row.
    assert decode_with_filters([(0, row), (4, bytes(16))]) == row * 2


@pytest.mark.parametrize(
    "mutate,fragment",
    [
        # A palette PNG (colour type 3) has no alpha channel to build an icon
        # from, so it is refused rather than read as if it had one.
        (lambda h: h[:9] + bytes([3]) + h[10:], "colour type 3"),
        # 16 bits per channel: the decoder reads 8, and reading a 16-bit image
        # as 8-bit silently halves the picture.
        (lambda h: h[:8] + bytes([16]) + h[9:], "16 bits per channel"),
        # Adam7 interlacing stores the image as seven interleaved passes.
        (lambda h: h[:12] + bytes([1]), "interlaced"),
    ],
)
def test_the_decoder_refuses_an_image_it_cannot_read(mutate, fragment):
    """Each refusal names what it found (docs/method/METHOD.md section 5)."""
    data = bytearray(png_bytes(2, 2, TINY_ROWS))
    # The IHDR body is the 13 bytes after the 8-byte signature, the 4-byte
    # length and the 4-byte chunk type: offsets 16 to 28.
    data[16:29] = mutate(bytes(data[16:29]))

    with pytest.raises(make_icon.IconError) as raised:
        make_icon.decode_png_rgba8(bytes(data))
    assert fragment in str(raised.value)


def test_the_decoder_refuses_something_that_is_not_a_png():
    with pytest.raises(make_icon.IconError) as raised:
        make_icon.decode_png_rgba8(b"GIF89a not a png at all")
    assert "PNG signature" in str(raised.value)


