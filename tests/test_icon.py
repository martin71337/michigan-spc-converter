def test_the_master_artwork_is_the_image_the_design_records():
    """docs/DESIGN.md amendment #15 note 1: 1024x1024, 8-bit RGBA.

    Read from the committed file, so replacing the artwork with something of a
    different shape fails here rather than producing a distorted icon.
    """
    width, height, pixels = make_icon.decode_png_rgba8(
        make_icon.MASTER_PNG.read_bytes()
    )
    assert (width, height) == (1024, 1024)
    assert len(pixels) == 1024 * 1024 * 4


def test_generating_from_the_master_produces_the_six_windows_sizes(tmp_path):
    """16, 32, 48, 64, 128, 256 - the sizes Windows asks for."""
    written = make_icon.generate(output=tmp_path / "coord-convert.ico")

    assert written.exists()
    # Nothing partial survives: the staged file is renamed, not left behind.
    assert [p.name for p in tmp_path.iterdir()] == ["coord-convert.ico"]

    entries = read_ico_directory(written.read_bytes())
    assert [e["width"] for e in entries] == list(sorted(make_icon.ICON_SIZES))
    for entry in entries:
        assert entry["height"] == entry["width"]
        assert entry["bits"] == 32
        # Each body is its 40-byte header, size*size*4 of BGRA, and a 1-bit
        # mask padded to 4 bytes a row.
        size = entry["width"]
        mask = ((size + 31) // 32) * 4 * size
        assert entry["length"] == 40 + size * size * 4 + mask


def test_qt_reads_every_size_out_of_the_generated_icon(qapp, tmp_path):
    """The consumer that matters most here reads it back.

    A container that parses in this file's own reader but not in Qt's would be
    a test agreeing with itself. QIcon is the shipped window icon's own loader.
    """
    from PySide6.QtGui import QIcon

    written = make_icon.generate(output=tmp_path / "coord-convert.ico")
    loaded = QIcon(str(written))

    assert loaded.isNull() is False
    sizes = sorted(size.width() for size in loaded.availableSizes())
    assert sizes == list(sorted(make_icon.ICON_SIZES))


def test_the_generator_refuses_a_master_that_is_not_there(tmp_path):
    with pytest.raises(make_icon.IconError) as raised:
        make_icon.generate(master=tmp_path / "no-such-art.png")
    assert "master artwork is missing" in str(raised.value)


