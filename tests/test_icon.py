def png_bytes(width: int, height: int, rows: list[bytes]) -> bytes:
    """Assemble a minimal 8-bit RGBA PNG from raw, unfiltered scanlines.

    Written here rather than generated by the code under test, so the decoder
    below is checked against bytes this file chose.
    """

    def chunk(kind: bytes, body: bytes) -> bytes:
        return (
            struct.pack(">I", len(body))
            + kind
            + body
            + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)
        )

    # colour type 6 (RGBA), bit depth 8, compression 0, filter 0, interlace 0
    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    raw = b"".join(b"\x00" + row for row in rows)  # filter type 0 per scanline
    return (
        b"\x89PNG\r\n\x1a\x0a"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw))
        + chunk(b"IEND", b"")
    )


# A 2x2 RGBA image, chosen so that every channel and the alpha behave
# differently under averaging:
#
#   (255,0,0,255)  opaque red        (0,255,0,255)  opaque green
#   (0,0,255,128)  half-alpha blue   (255,255,255,0) fully transparent white
TINY_ROWS = [
    bytes([255, 0, 0, 255, 0, 255, 0, 255]),
    bytes([0, 0, 255, 128, 255, 255, 255, 0]),
]


