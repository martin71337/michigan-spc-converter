"""The icon build step, and the loader that reads what it produces.

The icon is the one artefact in this program that is allowed to be missing, and
the one whose absence must never stop the window opening. Two properties
therefore dominate this file: the generator produces a container Windows and Qt
can actually read, and the loader degrades quietly when it has not been run.

There is a third, quieter property. The ``.ico`` is *derived* from the committed
master rather than committed beside it, so that the two cannot disagree about
what the program looks like (docs/DESIGN.md amendment #15 note 1). That only
holds while the generator's output path and the loader's search path are the
same path, so that is pinned below rather than left to memory.

Every expected value is hand-derived in the comment above it
(docs/method/METHOD.md section 4).
"""

